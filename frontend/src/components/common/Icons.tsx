export const HeadingIcon: React.FC<IconProps> = ({ size, level, ...props }) => {
  // If size is provided, use it. Otherwise calculate based on level (H1=22, H6=14.5)
  const finalSize = size || (level ? (22 - (level - 1) * 1.5) : 18);
  
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={finalSize}
      height={finalSize}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className="icon-svg"
      {...props}
    >
      {level ? (
        <text
          x="12"
          y="16.5"
          textAnchor="middle"
          fontSize={level === 1 ? 14 : level === 2 ? 13.5 : level === 3 ? 12.5 : 11.5}
          fontWeight="900"
          fill="currentColor"
          stroke="none"
        >
          {`H${level}`}
        </text>
      ) : (
        <>
          <path d="M6 12h12" />
          <path d="M6 20V4" />
          <path d="M18 20V4" />
        </>
      )}
    </svg>
  );
};

